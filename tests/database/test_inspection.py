def test_atomic_publication_writes_identical_bytes_from_destination_directory(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    database_path = tmp_path / "database.db"
    output_path = tmp_path / "published" / "schema.md"
    output_path.parent.mkdir()
    _make_arbitrary_database(database_path)
    replacements: list[tuple[Path, Path]] = []
    original_replace = os.replace

    def record_replace(
        source: str | bytes | os.PathLike[str],
        destination: str | bytes | os.PathLike[str],
    ) -> None:
        source_path = Path(source)
        destination_path = Path(destination)
        replacements.append((source_path, destination_path))
        original_replace(source, destination)

    monkeypatch.setattr("chess_move_trainer.database.publication.os.replace", record_replace)

    published = publish_schema(database_path, output_path)

    assert output_path.read_bytes() == published
    assert replacements == [(replacements[0][0], output_path)]
    assert replacements[0][0].parent == output_path.parent
    assert replacements[0][0] != output_path


def test_existing_output_survives_inspection_render_and_write_failures(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    database_path = tmp_path / "database.db"
    output_path = tmp_path / "schema.md"
    _make_arbitrary_database(database_path)
    original_output = b"keep this reference"
    output_path.write_bytes(original_output)

    monkeypatch.setattr(
        "chess_move_trainer.database.publication.render_schema_markdown",
        lambda inspection: (_ for _ in ()).throw(RuntimeError("render failed")),
    )
    with pytest.raises(RuntimeError, match="render failed"):
        publish_schema(database_path, output_path)
    assert output_path.read_bytes() == original_output

    monkeypatch.undo()

    def fail_replace(source: object, destination: object) -> None:
        raise OSError("write failed")

    monkeypatch.setattr("chess_move_trainer.database.publication.os.replace", fail_replace)
    with pytest.raises(OSError, match="write failed"):
        publish_schema(database_path, output_path)
    assert output_path.read_bytes() == original_output

    malformed_database = tmp_path / "malformed.db"
    malformed_database.write_bytes(b"not a sqlite database")
    with pytest.raises(Exception):
        publish_schema(malformed_database, output_path)
    assert output_path.read_bytes() == original_output


def test_output_database_collision_is_rejected_without_damage(tmp_path: Path) -> None:
    database_path = tmp_path / "database.db"
    _make_arbitrary_database(database_path)
    original_bytes = database_path.read_bytes()
    alias_path = tmp_path / "database-alias.db"
    os.link(database_path, alias_path)

    with pytest.raises(ValueError, match="selected database"):
        publish_schema(database_path, alias_path)

    assert database_path.read_bytes() == original_bytes
    assert alias_path.read_bytes() == original_bytes


def test_output_parent_must_exist_and_existing_output_is_untouched(tmp_path: Path) -> None:
    database_path = tmp_path / "database.db"
    _make_arbitrary_database(database_path)
    output_path = tmp_path / "missing" / "schema.md"

    with pytest.raises(FileNotFoundError):
        publish_schema(database_path, output_path)

    assert not output_path.parent.exists()
